// Checks the joint-load metrics against the database and writes docs/validation.md.
//   node scripts/validate.ts
//
// A finishing transition ("tap", "finish") of a submission kind should reach the danger
// range on the joint its kind attacks. Every other transition is measured too, on all
// joints of both players, to show how often a metric fires where nothing is attacked;
// that is why the viewer only lights the joint the technique attacks.
import { readFileSync, writeFileSync } from "node:fs";
import { ContactSolver } from "@bjj3d/core/contact";
import { buildGraph, parse } from "@bjj3d/grapplemap";
import { defaultMetrics, landmarksFromPlayer, read, SIDED, submissionKind, type Kind, type Landmarks, type Side } from "@bjj3d/metrics";

const root = new URL("../../../", import.meta.url);
const graph = buildGraph(parse(readFileSync(new URL("data/grapplemap/GrappleMap.txt", root), "utf8")));
// Measured on what the viewer shows: poses after the contact solver.
const solver = new ContactSolver(JSON.parse(readFileSync(new URL("data/body/capsules.json", root), "utf8")));
const solved = graph.transitions.map((t) => solver.transition(t.block.poses).map((p) => p.map(landmarksFromPlayer) as [Landmarks, Landmarks]));
// Every kind in the registry, so a new submission is checked the same way as the built-ins.
const KINDS: Kind[] = defaultMetrics.ids;

/** Finishes that miss, and why: in each case the GrappleMap animation never gets there. */
const KNOWN_MISSES: Record<number, string> = {
  32008: "the knee is only straight once both players have stood up apart",
  13480: "the arm is straight (8° of flexion), so the forearm cannot show the shoulder's rotation",
  13170: "nothing of the opponent comes closer than 15 cm to the throat",
  13563: "nothing of the opponent comes closer than 15 cm to the throat",
  31626: "the second limb stays 14 cm from the throat",
};

/** Highest reading over a clip, over both players and sides (as the viewer picks its target). */
function peak(kind: Kind, frames: [Landmarks, Landmarks][]) {
  let best = { value: 0, danger: false };
  for (const f of frames)
    for (const p of [0, 1])
      for (const s of (SIDED[kind] ? ["Left", "Right"] : ["Left"]) as Side[]) {
        const r = read(kind, f[p], f[1 - p], s);
        if (r.value > best.value) best = { value: r.value, danger: best.danger || r.danger };
        else if (r.danger) best.danger = true;
      }
  return best;
}

const rows: string[] = [];
const finishes: string[] = [];
let finishTotal = 0, finishDanger = 0;
for (const kind of KINDS) {
  let tagged = 0, taggedDanger = 0, other = 0, otherDanger = 0;
  for (const [ti, t] of graph.transitions.entries()) {
    const frames = solved[ti];
    const k = submissionKind(t.block.tags, t.from === null ? [] : graph.positions[t.from].tags, t.to === null ? [] : graph.positions[t.to].tags);
    const r = peak(kind, frames);
    if (k === kind) {
      tagged++;
      if (r.danger) taggedDanger++;
      if (/tap|finish|submit/i.test(t.block.name)) {
        finishTotal++;
        if (r.danger) finishDanger++;
        const from = t.from === null ? "?" : graph.positions[t.from].name;
        const note = r.danger ? "" : KNOWN_MISSES[t.block.line] ?? "not explained yet";
        finishes.push(`| ${t.block.line} | ${from} → ${t.block.name} | ${kind} | ${r.value.toFixed(2)} | ${r.danger ? "yes" : "no"} | ${note} |`);
      }
    } else if (!k) {
      other++;
      if (r.danger) otherDanger++;
    }
  }
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "–");
  rows.push(`| ${kind} | ${tagged} | ${taggedDanger} (${pct(taggedDanger, tagged)}) | ${other} | ${otherDanger} (${pct(otherDanger, other)}) |`);
}

const md = `# Validation of the joint-load metrics

Generated by \`node packages/data/scripts/validate.ts\` from \`data/grapplemap/GrappleMap.txt\`, after
the contact solver (\`packages/core/src/contact.ts\`), as the viewer shows it; the thresholds are in
\`packages/metrics/src/metrics.ts\`. GrappleMap has no forces, so these are geometric
readings (angles, distances), not measurements of load.

## Finishing transitions

Transitions named "tap" or "finish" whose own tags, or the tags of the positions they join,
name a submission. Each should reach the danger range somewhere in the clip.

${finishDanger} of ${finishTotal} reach it.

| line | transition | kind | peak value | danger | why not |
|---|---|---|---|---|---|
${finishes.join("\n")}

## All transitions

"Tagged" counts transitions tied to a submission of that kind (setups, escapes and finishes).
"Untagged" counts transitions tied to no submission at all; a reading in the danger range there
is a false alarm, which is why the viewer lights only the joint that the technique attacks.

| kind | tagged | in danger | untagged | in danger (false alarm) |
|---|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync(new URL("docs/validation.md", root), md);
console.log(`finishes in danger: ${finishDanger}/${finishTotal}`);
console.log(rows.join("\n"));
